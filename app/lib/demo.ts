/**
 * Replay the run to a named moment. Drives `?at=` on the board, for screenshots,
 * stageshow product shots and the video.
 */
export type Moment = "drift" | "planned" | "handoff" | "applied" | "verified";
export function boardAt(at: Moment): BoardState {
  let s = demoBoard;
  const run = (a: Action) => {
    s = reduce(s, a);
  };
  if (at === "drift") return s;
  run({ type: "plan" });
  if (at === "planned") return s;
  run({ type: "start" });
  for (const step of STEPS) {
    if (s.phase === "handoff") {
      if (at === "handoff") break;
      run({ type: "handoff-done", id: "meta" });
    }
    run({ type: "activate", id: step.id });
    run({ type: "settle", id: step.id });
  }
  if (at === "handoff") {
    return {
      ...s,
      strips: Object.fromEntries(
        Object.entries(s.strips).map(([k, v]) => [k, { ...v, fresh: false }]),
      ),
    };
  }
  run({ type: "apply-done" });
  if (at === "applied")
    return {
      ...s,
      strips: Object.fromEntries(
        Object.entries(s.strips).map(([k, v]) => [k, { ...v, fresh: false }]),
      ),
    };
  run({ type: "verify-start" });
  for (const step of STEPS) {
    run({ type: "check", id: step.id });
    run({ type: "checked", id: step.id });
  }
  run({ type: "verify-done" });
  return {
    ...s,
    strips: Object.fromEntries(
      Object.entries(s.strips).map(([k, v]) => [k, { ...v, fresh: false }]),
    ),
  };
}
