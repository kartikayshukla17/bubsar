export type StripState = { bay: BayId | null; mark: Mark; fresh: boolean; note?: string };

export type BoardState = {
  phase: Phase;
  strips: Record<string, StripState>;
  cursor: number; // next step index to apply
  focus: ValueId;
};

export const initialBoard: BoardState = {
  phase: "drift",
  strips: Object.fromEntries(STEPS.map((s) => [s.id, { bay: null, mark: "drift", fresh: false }])),
  cursor: 0,
  focus: "tunnel.url",
};

export type Action =
  | { type: "plan" }
  | { type: "discard" }
  | { type: "start" }
  | { type: "activate"; id: string }
  | { type: "settle"; id: string }
  | { type: "handoff-done"; id: string }
  | { type: "apply-done" }
  | { type: "verify-start" }
  | { type: "check"; id: string }
  | { type: "checked"; id: string }
  | { type: "verify-done" }
  | { type: "focus"; value: ValueId }
  | { type: "reset" };

const patch = (s: BoardState, id: string, next: Partial<StripState>): BoardState => ({
  ...s,
  strips: { ...s.strips, [id]: { ...s.strips[id], fresh: false, ...next } },
});

export function reduce(s: BoardState, a: Action): BoardState {
  switch (a.type) {
    case "plan":
      return {
        ...s,
        phase: "planned",
        strips: Object.fromEntries(STEPS.map((st) => [st.id, { bay: "plan", mark: "planned", fresh: false }])),
      };
    case "discard":
      return { ...initialBoard, focus: s.focus };
    case "start":
      return { ...s, phase: "applying" };
    case "activate": {
      const step = STEPS.find((x) => x.id === a.id);
      return patch(s, a.id, { bay: "active", mark: "active", note: step?.activeNote });
    }
    case "settle": {
      const step = STEPS.find((x) => x.id === a.id);
      const idx = STEPS.findIndex((x) => x.id === a.id);
      if (step?.handoff) {
        return { ...patch(s, a.id, { bay: "turn", mark: "handoff", fresh: true }), phase: "handoff", cursor: idx + 1 };
      }
      return { ...patch(s, a.id, { bay: "cleared", mark: "applied", fresh: true, note: undefined }), cursor: idx + 1 };
    }
    case "handoff-done":
      return { ...patch(s, a.id, { bay: "cleared", mark: "applied", fresh: true, note: undefined }), phase: "applying" };
    case "apply-done":
      return { ...s, phase: "applied" };
    case "verify-start":
      return { ...s, phase: "verifying" };
    case "check":
      return patch(s, a.id, { mark: "checking" });
    case "checked": {
      const step = STEPS.find((x) => x.id === a.id);
      return patch(s, a.id, { mark: step?.verify.mark ?? "verified", fresh: true, note: step?.verify.note });
    }
    case "verify-done":
      return { ...s, phase: "verified" };
    case "focus":
      return { ...s, focus: a.value };
    case "reset":
      return initialBoard;
  }
}

/**
 * Replay the run to a named moment. Drives `?at=` on the board, for screenshots,
 * stageshow product shots and the video.
 */
export type Moment = "drift" | "planned" | "handoff" | "applied" | "verified";
export function boardAt(at: Moment): BoardState {
  let s = initialBoard;
  const run = (a: Action) => {
    s = reduce(s, a);
  };
  if (at === "drift") return s;
  run({ type: "plan" });
  if (at === "planned") return s;
  run({ type: "start" });
  for (const step of STEPS) {
    if (s.phase === "handoff") {
      if (at === "handoff") break;
      run({ type: "handoff-done", id: "meta" });
    }
    run({ type: "activate", id: step.id });
    run({ type: "settle", id: step.id });
  }
  if (at === "handoff") {
    return { ...s, strips: Object.fromEntries(Object.entries(s.strips).map(([k, v]) => [k, { ...v, fresh: false }])) };
  }
  run({ type: "apply-done" });
  if (at === "applied") return { ...s, strips: Object.fromEntries(Object.entries(s.strips).map(([k, v]) => [k, { ...v, fresh: false }])) };
  run({ type: "verify-start" });
  for (const step of STEPS) {
    run({ type: "check", id: step.id });
    run({ type: "checked", id: step.id });
  }
  run({ type: "verify-done" });
  return { ...s, strips: Object.fromEntries(Object.entries(s.strips).map(([k, v]) => [k, { ...v, fresh: false }])) };
}

/** State of the route value → destination, as the sector map draws it. */
export function routeMark(s: BoardState, value: Value, dest: DestinationId): Mark {
  if (value.id === "tunnel.url") {
    const step = STEPS.find((x) => x.destination === dest);
    return step ? s.strips[step.id].mark : "unknown";
  }
  if (value.id === "WHATSAPP_VERIFY_TOKEN" && dest === "meta") {
    const m = s.strips.meta.mark;
    return m === "drift" || m === "planned" ? "verified" : m;
  }
  return value.rest;
}

export function valueMark(s: BoardState, value: Value): Mark {
  const marks = value.routes.map((d) => routeMark(s, value, d));
  const order: Mark[] = ["drift", "handoff", "active", "checking", "planned", "unknown", "unexercised", "applied", "verified"];
  for (const m of order) if (marks.includes(m)) return m;
  return "verified";
}

export function stepTouches(step: Step, value: ValueId) {
  return value === "tunnel.url" || (step.alsoWrites ?? []).includes(value);
}
